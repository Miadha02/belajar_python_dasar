#reamur

reamur = float(input('masukkan nilai suhu dalam reamur : '))
print("suhu : ",reamur,'reamur')

celcius = (5/4) * reamur
print('suhu : ',celcius,'celcius')

fahrenheit = ((9/5)*celcius)+32
print('suhu : ',fahrenheit,'fahrenheit')

kelvin = celcius + 273
print('suhu : ',kelvin,'kelvin')